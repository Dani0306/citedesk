import {
  CONFIG_LABELS,
  EvidenceSummary,
  formatMs,
  formatPercent,
  formatPoints,
  formatUsd,
  MIN_EVIDENCE_QUESTIONS,
  MIN_JUDGED_OUTPUTS,
  MIN_UNANSWERABLE,
  type EvidenceRow,
} from "../lib/evidence";
import { CELL_MEANING, diagnose } from "./diagnosis";
import type { GenerationRun, JudgeRun, RetrievalRun } from "./schema";

// The ablation report (T27). Every number comes from a run file: for each config, the latest run
// on the current question set, and only if that set is the full one. Rendering is deterministic
// (no timestamps), so `eval:report --check` can compare it byte for byte.

export const START = "<!-- ablation:start -->";
export const END = "<!-- ablation:end -->";
export const DIAGNOSIS_START = "<!-- diagnosis:start -->";
export const DIAGNOSIS_END = "<!-- diagnosis:end -->";

const ORDER = ["vector", "hybrid", "hybrid-rerank"];
const byOrder = (a: string, b: string) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b);

export function buildSummary(runs: { file: string; run: RetrievalRun }[], questionsHash: string, questionCount: number): EvidenceSummary {
  const latest = new Map<string, { file: string; run: RetrievalRun }>();
  if (questionCount >= MIN_EVIDENCE_QUESTIONS) {
    for (const r of runs) {
      if (r.run.questionsHash !== questionsHash || r.run.questionCount < MIN_EVIDENCE_QUESTIONS) continue;
      const seen = latest.get(r.run.config.name);
      if (!seen || r.run.createdAt > seen.run.createdAt) latest.set(r.run.config.name, r);
    }
  }
  const rows: EvidenceRow[] = [...latest.values()]
    .sort((a, b) => byOrder(a.run.config.name, b.run.config.name))
    .map(({ file, run }) => ({
      config: run.config.name,
      recallAt5: run.metrics.recallAt5,
      recallAt20: run.metrics.recallAt20,
      mrr: run.metrics.mrr,
      ndcgAt10: run.metrics.ndcgAt10,
      costPerQueryUsd: run.costPerQueryUsd,
      p95LatencyMs: run.latencyMs.p95,
      runFile: file,
      runDate: run.createdAt.slice(0, 10),
    }));
  return EvidenceSummary.parse({ questionsHash, questionCount, minQuestions: MIN_EVIDENCE_QUESTIONS, rows });
}

const latestBy = <T extends { createdAt: string }>(items: { file: string; run: T }[]) =>
  items.reduce<{ file: string; run: T } | null>((best, r) => (!best || r.run.createdAt > best.run.createdAt ? r : best), null);

/** The latest generation run on the full current set (40 answerable + 10 unanswerable), and the latest judge run on it with 30 outputs. */
export function selectGeneration(
  gens: { file: string; run: GenerationRun }[],
  judges: { file: string; run: JudgeRun }[],
  questionsHash: string,
): { gen: { file: string; run: GenerationRun } | null; judge: { file: string; run: JudgeRun } | null } {
  const gen = latestBy(
    gens.filter((g) => g.run.questionsHash === questionsHash && g.run.answerableCount >= MIN_EVIDENCE_QUESTIONS && g.run.unanswerableCount >= MIN_UNANSWERABLE),
  );
  const judge = gen ? latestBy(judges.filter((j) => j.run.generationRun === gen.file && j.run.outputsJudged >= MIN_JUDGED_OUTPUTS)) : null;
  return { gen, judge };
}

export function withGeneration(summary: EvidenceSummary, picked: ReturnType<typeof selectGeneration>): EvidenceSummary {
  const { gen, judge } = picked;
  return EvidenceSummary.parse({
    ...summary,
    generation: gen && {
      config: gen.run.config.name,
      hallucinatedCitations: gen.run.metrics.hallucinatedCitations,
      citationPrecision: gen.run.metrics.citationPrecision,
      correctRefusalRate: gen.run.metrics.correctRefusalRate,
      falseRefusalRate: gen.run.metrics.falseRefusalRate,
      runFile: gen.file,
      runDate: gen.run.createdAt.slice(0, 10),
    },
    judge: judge && {
      model: judge.run.model,
      agreement: judge.run.agreement.agreement,
      kappa: judge.run.agreement.kappa,
      sentences: judge.run.agreement.sentences,
      runFile: judge.file,
      runDate: judge.run.createdAt.slice(0, 10),
    },
  });
}

/** The README diagnosis block (T37): retrieval hit × grounded answer, plus refusals and the code-checked counts. */
export function renderDiagnosis(picked: ReturnType<typeof selectGeneration>, answerable: number, unanswerable: number): string {
  const lines = [DIAGNOSIS_START, "_Generated by `npm run eval:report` from the run files in `evals/runs/`. Don't edit by hand._", ""];
  const { gen, judge } = picked;
  if (!gen) {
    lines.push(
      `**Pending:** needs a generation run on ${MIN_EVIDENCE_QUESTIONS} answerable and ${MIN_UNANSWERABLE} unanswerable questions (the set has ${answerable} and ${unanswerable}).`,
    );
  } else {
    const d = diagnose(gen.run, judge?.run ?? null);
    const m = gen.run.metrics;
    const cell = (k: keyof typeof d.cells) => `${d.cells[k]} · ${CELL_MEANING[k]}`;
    lines.push(
      `Generation run [${gen.file}](evals/runs/${gen.file}) (\`${gen.run.config.name}\`): ${gen.run.answerableCount} answerable and ${gen.run.unanswerableCount} unanswerable questions.`,
      "",
      `- Hallucinated citations (a marker pointing at no retrieved source, checked in code): **${m.hallucinatedCitations}** (target 0)`,
      `- Citation precision (cited sections that are labelled): ${m.citationPrecision === null ? "n/a" : formatPercent(m.citationPrecision)}`,
      `- Correct refusals of unanswerable questions: ${m.correctRefusalRate === null ? "n/a" : formatPercent(m.correctRefusalRate)} · false refusals of answerable ones: ${m.falseRefusalRate === null ? "n/a" : formatPercent(m.falseRefusalRate)}`,
      "",
    );
    if (!judge) {
      lines.push(`**Groundedness pending:** needs a judge run on ${MIN_JUDGED_OUTPUTS} hand-labelled outputs of this run.`);
    } else {
      const a = judge.run.agreement;
      lines.push(
        `Groundedness judged by \`${judge.run.model}\` ([${judge.file}](evals/runs/${judge.file})): ${a.agreement === null ? "n/a" : formatPercent(a.agreement)} agreement with ${a.sentences} hand-labelled sentences, Cohen's κ ${a.kappa === null ? "n/a" : a.kappa.toFixed(2)}.`,
        "",
        "| | Grounded | Not grounded |",
        "| --- | --- | --- |",
        `| Retrieved the labelled section | ${cell("hitGrounded")} | ${cell("hitUngrounded")} |`,
        `| Missed it | ${cell("missGrounded")} | ${cell("missUngrounded")} |`,
        "",
        `Not in the table: ${d.unjudged} answered but not judged, ${d.falseRefusals} false refusals, ${d.correctRefusals} correct refusals, ${d.answeredUnanswerable} unanswerable questions answered anyway.`,
      );
    }
  }
  lines.push(DIAGNOSIS_END);
  return lines.join("\n");
}

export function renderAblation(summary: EvidenceSummary): string {
  const lines = [START, "_Generated by `npm run eval:report` from the run files in `evals/runs/`. Don't edit by hand._", ""];
  if (summary.rows.length === 0) {
    lines.push(
      summary.questionCount < summary.minQuestions
        ? `**Pending:** the question set has ${summary.questionCount} of ${summary.minQuestions} labelled questions. Runs on a smaller set are plumbing checks and aren't reported.`
        : "**Pending:** no retrieval run on the current question set yet.",
    );
  } else {
    lines.push(
      `Retrieval on ${summary.questionCount} labelled questions (set \`${summary.questionsHash.slice(0, 12)}\`). Recall, MRR and nDCG are in points (×100); cost and p95 latency are per query.`,
      "",
      "| Configuration | Recall@5 | Recall@20 | MRR | nDCG@10 | Cost / query | p95 latency | Run |",
      "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
      ...summary.rows.map(
        (r) =>
          `| ${CONFIG_LABELS[r.config] ?? r.config} | ${formatPoints(r.recallAt5)} | ${formatPoints(r.recallAt20)} | ${formatPoints(r.mrr)} | ${formatPoints(r.ndcgAt10)} | ${formatUsd(r.costPerQueryUsd)} | ${formatMs(r.p95LatencyMs)} | [${r.runFile}](evals/runs/${r.runFile}) |`,
      ),
    );
  }
  lines.push(END);
  return lines.join("\n");
}

/** Replaces the block between the markers; throws if they're missing or out of order. */
export function replaceBlock(readme: string, block: string, start = START, end = END): string {
  const i = readme.indexOf(start);
  const j = readme.indexOf(end);
  if (i === -1 || j === -1 || j < i) throw new Error(`README.md needs ${start} … ${end} markers`);
  return readme.slice(0, i) + block + readme.slice(j + end.length);
}

export function renderSummaryJson(summary: EvidenceSummary): string {
  return `${JSON.stringify(summary, null, 2)}\n`;
}
