import { CONFIG_LABELS, EvidenceSummary, formatMs, formatPoints, formatUsd, MIN_EVIDENCE_QUESTIONS, type EvidenceRow } from "../lib/evidence";
import type { RetrievalRun } from "./schema";

// The ablation report (T27). Every number comes from a run file: for each config, the latest run
// on the current question set, and only if that set is the full one. Rendering is deterministic
// (no timestamps), so `eval:report --check` can compare it byte for byte.

export const START = "<!-- ablation:start -->";
export const END = "<!-- ablation:end -->";

const ORDER = ["vector", "hybrid", "hybrid-rerank"];
const byOrder = (a: string, b: string) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b);

export function buildSummary(runs: { file: string; run: RetrievalRun }[], questionsHash: string, questionCount: number): EvidenceSummary {
  const latest = new Map<string, { file: string; run: RetrievalRun }>();
  if (questionCount >= MIN_EVIDENCE_QUESTIONS) {
    for (const r of runs) {
      if (r.run.questionsHash !== questionsHash || r.run.questionCount < MIN_EVIDENCE_QUESTIONS) continue;
      const seen = latest.get(r.run.config.name);
      if (!seen || r.run.createdAt > seen.run.createdAt) latest.set(r.run.config.name, r);
    }
  }
  const rows: EvidenceRow[] = [...latest.values()]
    .sort((a, b) => byOrder(a.run.config.name, b.run.config.name))
    .map(({ file, run }) => ({
      config: run.config.name,
      recallAt5: run.metrics.recallAt5,
      recallAt20: run.metrics.recallAt20,
      mrr: run.metrics.mrr,
      ndcgAt10: run.metrics.ndcgAt10,
      costPerQueryUsd: run.costPerQueryUsd,
      p95LatencyMs: run.latencyMs.p95,
      runFile: file,
      runDate: run.createdAt.slice(0, 10),
    }));
  return EvidenceSummary.parse({ questionsHash, questionCount, minQuestions: MIN_EVIDENCE_QUESTIONS, rows });
}

export function renderAblation(summary: EvidenceSummary): string {
  const lines = [START, "_Generated by `npm run eval:report` from the run files in `evals/runs/`. Don't edit by hand._", ""];
  if (summary.rows.length === 0) {
    lines.push(
      summary.questionCount < summary.minQuestions
        ? `**Pending:** the question set has ${summary.questionCount} of ${summary.minQuestions} labelled questions. Runs on a smaller set are plumbing checks and aren't reported.`
        : "**Pending:** no retrieval run on the current question set yet.",
    );
  } else {
    lines.push(
      `Retrieval on ${summary.questionCount} labelled questions (set \`${summary.questionsHash.slice(0, 12)}\`). Recall, MRR and nDCG are in points (×100); cost and p95 latency are per query.`,
      "",
      "| Configuration | Recall@5 | Recall@20 | MRR | nDCG@10 | Cost / query | p95 latency | Run |",
      "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
      ...summary.rows.map(
        (r) =>
          `| ${CONFIG_LABELS[r.config] ?? r.config} | ${formatPoints(r.recallAt5)} | ${formatPoints(r.recallAt20)} | ${formatPoints(r.mrr)} | ${formatPoints(r.ndcgAt10)} | ${formatUsd(r.costPerQueryUsd)} | ${formatMs(r.p95LatencyMs)} | [${r.runFile}](evals/runs/${r.runFile}) |`,
      ),
    );
  }
  lines.push(END);
  return lines.join("\n");
}

/** Replaces the block between the markers; throws if they're missing or out of order. */
export function replaceBlock(readme: string, block: string): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error(`README.md needs ${START} … ${END} markers`);
  return readme.slice(0, start) + block + readme.slice(end + END.length);
}

export function renderSummaryJson(summary: EvidenceSummary): string {
  return `${JSON.stringify(summary, null, 2)}\n`;
}
